/* MIYAR Public Health RC18.2 - Service Worker (sw-rc18-2.js)
   Cache-first for the app shell, network fallback, offline-safe.
   Registration in MIYAR-RC18.2.html points to this exact lowercase filename. */
var CACHE_NAME = 'miyar-rc18-2-v1';
var APP_SHELL = ['./', './MIYAR-RC18.2.html', './manifest-rc18-2.json'];

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE_NAME).then(function (cache) {
      return Promise.all(APP_SHELL.map(function (url) {
        return cache.add(url).catch(function () { /* skip missing assets, never fail install */ });
      }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.filter(function (k) { return k !== CACHE_NAME; })
        .map(function (k) { return caches.delete(k); }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function (event) {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request, { ignoreSearch: true }).then(function (cached) {
      if (cached) return cached;
      return fetch(event.request).then(function (response) {
        if (response && response.ok && response.type === 'basic') {
          var copy = response.clone();
          caches.open(CACHE_NAME).then(function (cache) { cache.put(event.request, copy); });
        }
        return response;
      }).catch(function () {
        return caches.match('./MIYAR-RC18.2.html');
      });
    })
  );
});
